"""Compliance report as PDF, built from live data."""
import io
from datetime import timedelta

from django.db.models import Count
from django.http import HttpResponse
from django.utils import timezone
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
from rest_framework.decorators import api_view, permission_classes

from ..models import DPORecord, Employee, Event, Incident, Report, Rule
from ..permissions import IsAdminOrComplianceOfficer
from .officer import employee_risk_rows, kpis

SEVERITY_COLOURS = {
    'CRITICAL': colors.HexColor('#b42318'),
    'HIGH': colors.HexColor('#c4320a'),
    'MEDIUM': colors.HexColor('#b54708'),
    'LOW': colors.HexColor('#475467'),
}


def _table(rows, widths, header_bg='#101828'):
    table = Table(rows, colWidths=widths, repeatRows=1)
    table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor(header_bg)),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, -1), 8),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#f2f4f7')]),
        ('GRID', (0, 0), (-1, -1), 0.25, colors.HexColor('#d0d5dd')),
        ('LEFTPADDING', (0, 0), (-1, -1), 4),
        ('RIGHTPADDING', (0, 0), (-1, -1), 4),
    ]))
    return table


@api_view(['GET'])
@permission_classes([IsAdminOrComplianceOfficer])
def compliance_report(request):
    days = max(1, min(90, int(request.query_params.get('days', 7))))
    employee_id = request.query_params.get('employee')
    now = timezone.now()
    since = now - timedelta(days=days)

    incidents = Incident.objects.filter(detected_at__gte=since).select_related('employee', 'rule')
    employee = Employee.objects.filter(pk=employee_id).first() if employee_id else None
    if employee:
        incidents = incidents.filter(employee=employee)

    styles = getSampleStyleSheet()
    small = ParagraphStyle('small', parent=styles['BodyText'], fontSize=8, leading=10)
    h1 = ParagraphStyle('h1', parent=styles['Title'], fontSize=18, alignment=0, spaceAfter=2)
    h2 = ParagraphStyle('h2', parent=styles['Heading2'], fontSize=12, spaceBefore=10, spaceAfter=4)
    muted = ParagraphStyle('muted', parent=small, textColor=colors.HexColor('#667085'))

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, leftMargin=14 * mm, rightMargin=14 * mm,
                            topMargin=14 * mm, bottomMargin=14 * mm,
                            title='Auditra compliance report')
    story = [
        Paragraph('Auditra - GDPR compliance report', h1),
        Paragraph(
            f'Period: last {days} day(s), {timezone.localtime(since):%d %b %Y %H:%M} to '
            f'{timezone.localtime(now):%d %b %Y %H:%M} (Asia/Karachi). Generated by {request.user.username}.'
            + (f' Employee: {employee.full_name} ({employee.employee_code}).' if employee else ''), muted),
        Paragraph('Findings are potential violations and risk indicators detected from endpoint activity and '
                  'GDPR records. They are not legal determinations.', muted),
        Spacer(1, 6),
    ]

    k = kpis()
    by_sev = {row['severity']: row['n'] for row in incidents.exclude(kind='INDICATOR')
              .values('severity').annotate(n=Count('id'))}
    events_count = Event.objects.filter(occurred_at__gte=since)
    if employee:
        events_count = events_count.filter(employee=employee)
    summary = [
        ['Events analysed', 'Potential violations', 'Critical', 'High', 'Indicators', 'Officer precision'],
        [events_count.count(), incidents.exclude(kind='INDICATOR').count(), by_sev.get('CRITICAL', 0),
         by_sev.get('HIGH', 0), incidents.filter(kind='INDICATOR').count(),
         f"{k['precision']}% of {k['reviewed']} reviewed" if k['precision'] is not None else 'no reviews yet'],
    ]
    story += [Paragraph('Summary', h2), _table(summary, [30 * mm] * 5 + [32 * mm])]

    articles = {}
    for arts in incidents.exclude(kind='INDICATOR').exclude(status='FALSE_POSITIVE').values_list('articles', flat=True):
        for a in arts:
            articles[a] = articles.get(a, 0) + 1
    if articles:
        rows = [['GDPR article', 'Potential violations']]
        rows += [[a if a == 'Policy' else f'Art. {a}', n] for a, n in sorted(articles.items(), key=lambda x: -x[1])]
        story += [Paragraph('By GDPR article', h2), _table(rows, [60 * mm, 40 * mm])]

    if not employee:
        rows = [['Employee', 'Department', 'Open', 'Violations 7d', 'Max score', 'AI today']]
        for r in employee_risk_rows()[:15]:
            rows.append([r['full_name'], r['department'], r['open_incidents'], r['week_violations'],
                         r['risk_score'], '-' if r['ai_score_today'] is None else f"{r['ai_score_today']:.0f}"])
        story += [Paragraph('Employee risk', h2), _table(rows, [48 * mm, 32 * mm, 18 * mm, 26 * mm, 22 * mm, 22 * mm])]

    rows = [['Incident', 'When', 'Who', 'Articles', 'Score', 'Status', 'What happened']]
    for inc in incidents.order_by('-score', '-detected_at')[:80]:
        who = inc.employee.full_name if inc.employee else (inc.account or 'Organisation')
        rows.append([
            Paragraph(f'INC-{inc.number}<br/><font color="{SEVERITY_COLOURS[inc.severity].hexval()}">'
                      f'{inc.severity}</font>', small),
            timezone.localtime(inc.detected_at).strftime('%d %b %H:%M'),
            Paragraph(who, small),
            Paragraph(', '.join(inc.articles), small),
            inc.score,
            inc.get_status_display(),
            Paragraph(inc.summary, small),
        ])
    story += [Paragraph('Incidents (highest score first)', h2),
              _table(rows, [18 * mm, 20 * mm, 26 * mm, 18 * mm, 12 * mm, 20 * mm, 68 * mm])]

    dpo = DPORecord.objects.order_by('-updated_at').first()
    story += [
        Paragraph('Controls', h2),
        Paragraph(f"DPO designation: {dpo.compliance_status if dpo else 'MISSING'}. "
                  f"Rules enabled: {Rule.objects.filter(enabled=True).count()} of {Rule.objects.count()}. "
                  f"Agents online now: {k['agents_online']} of {k['agents_total']}.", small),
        Paragraph('Score = rule severity base (CRITICAL 70, HIGH 55, MEDIUM 35, LOW 15) + 5 per extra article '
                  '(max 10) + 10 outside shift + 10 special-category / national-ID data + up to 15 from the AI '
                  'anomaly score above 60 + 10 Art. 83 escalation (3 or more violations in 7 days), capped at 100.',
                  muted),
    ]

    doc.build(story)
    Report.objects.create(
        generated_by=request.user,
        period_covered=f'last {days} days' + (f' / {employee.employee_code}' if employee else ''),
        violation_summary=f'{incidents.exclude(kind="INDICATOR").count()} potential violations',
    )
    response = HttpResponse(buffer.getvalue(), content_type='application/pdf')
    name = f'auditra_report_{timezone.localtime(now):%Y%m%d_%H%M}.pdf'
    response['Content-Disposition'] = f'attachment; filename="{name}"'
    return response
